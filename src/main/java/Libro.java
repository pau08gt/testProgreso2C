public class Libro {
    private int codigo;
    private String titulo;
    private String autor;
    private int anioPublicacion;
    private double precio;

    public Libro(int codigo, String titulo, String autor, int anioPublicacion, double precio) {
        this.codigo = codigo;
        this.titulo = titulo;
        this.autor = autor;
        this.anioPublicacion = anioPublicacion;
        this.precio = precio;
    }

    
}
